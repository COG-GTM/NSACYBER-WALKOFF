// Builds parity/report/: one side-by-side PNG (baseline | upgraded | diff) per screenshot,
// pixel-diff percentages and README.md with the per-spec results of the last `playwright test` run.
const fs = require('fs');
const path = require('path');
const { PNG } = require('pngjs');
const pixelmatch = require('pixelmatch');

const root = path.join(__dirname, '..');
const shots = path.join(root, 'screenshots');
const out = path.join(root, 'report');
fs.mkdirSync(out, { recursive: true });

const read = f => PNG.sync.read(fs.readFileSync(f));
function pad(img, w, h) {
  const p = new PNG({ width: w, height: h });
  p.data.fill(255);
  PNG.bitblt(img, p, 0, 0, img.width, img.height, 0, 0);
  return p;
}

const names = fs.existsSync(path.join(shots, 'baseline'))
  ? fs.readdirSync(path.join(shots, 'baseline')).filter(f => f.endsWith('.png')).sort() : [];
const diffs = [];
for (const name of names) {
  const up = path.join(shots, 'upgraded', name);
  if (!fs.existsSync(up)) { diffs.push({ name, pct: null }); continue; }
  const a = read(path.join(shots, 'baseline', name));
  const b = read(up);
  const w = Math.max(a.width, b.width), h = Math.max(a.height, b.height);
  const pa = pad(a, w, h), pb = pad(b, w, h);
  const diff = new PNG({ width: w, height: h });
  const changed = pixelmatch(pa.data, pb.data, diff.data, w, h, { threshold: 0.1 });
  const gap = 16;
  const side = new PNG({ width: w * 3 + gap * 2, height: h });
  side.data.fill(255);
  PNG.bitblt(pa, side, 0, 0, w, h, 0, 0);
  PNG.bitblt(pb, side, 0, 0, w, h, w + gap, 0);
  PNG.bitblt(diff, side, 0, 0, w, h, (w + gap) * 2, 0);
  fs.writeFileSync(path.join(out, name), PNG.sync.write(side));
  diffs.push({ name, pct: (100 * changed) / (w * h), size: a.width === b.width && a.height === b.height ? '' : `${a.width}x${a.height} vs ${b.width}x${b.height}` });
}

const results = {};
const resultsFile = path.join(root, 'results.json');
if (fs.existsSync(resultsFile)) {
  const walk = (s, prefix) => {
    for (const spec of s.specs || []) for (const t of spec.tests) {
      const key = `${spec.file} › ${prefix}${spec.title}`;
      results[key] = results[key] || {};
      results[key][t.projectName] = t.results.length ? t.results[t.results.length - 1].status : 'skipped';
    }
    for (const c of s.suites || []) walk(c, c.title && !c.title.endsWith('.ts') ? `${prefix}${c.title} › ` : prefix);
  };
  for (const s of JSON.parse(fs.readFileSync(resultsFile, 'utf8')).suites) walk(s, '');
}

const count = (proj, st) => Object.values(results).filter(r => r[proj] === st).length;
let md = '# Parity report\n\nGenerated by `npm run report` from the last `npx playwright test` run.\n\n';
md += `| Project | Passed | Failed |\n|---|---|---|\n`;
for (const p of ['baseline', 'upgraded']) md += `| ${p} | ${count(p, 'passed')} | ${count(p, 'failed') + count(p, 'timedOut')} |\n`;
md += '\n## Specs\n\n| Spec | baseline | upgraded |\n|---|---|---|\n';
for (const [k, r] of Object.entries(results)) md += `| ${k} | ${r.baseline || '-'} | ${r.upgraded || '-'} |\n`;
md += '\n## Screenshots (baseline | upgraded | diff)\n\n| Page | Pixel diff | Note |\n|---|---|---|\n';
for (const d of diffs) md += `| [${d.name.replace('.png', '')}](${d.name}) | ${d.pct === null ? 'missing upgraded' : d.pct.toFixed(2) + '%'} | ${d.size || ''} |\n`;
fs.writeFileSync(path.join(out, 'README.md'), md);
console.log(md);
